/**
 * 核心表情（2026-10 主人指定）：贴表情/发表情的优先候选——randomEmojiLike 的兜底池
 * 与 react_emoji/send_face 工具描述示例都以本表为准；全量表照旧可用于名称解析。
 * 追加以主人的指定为准（ID 需存在于 EMOJI_LIKES；缺项自动忽略）。
 */
export const CORE_EMOJI_LIKES = ['361', '476', '234', '478', '479', '297', '339', '424', '379'] // 狗狗笑哭/不是吧/惊呆/对的对的/不对不对/拜谢/舔屏/续标识/企鹅流泪
  .map((id) => EMOJI_LIKES.find((e) => e.id === id))
  .filter(Boolean);

/**
 * 从核心表情表中随机取一个候选表情 ID（核心表为空时退回全量表）。
 * @returns {string} 候选表中的表情 ID
 */
export function randomEmojiLike() {
  const pool = CORE_EMOJI_LIKES.length ? CORE_EMOJI_LIKES : EMOJI_LIKES;
  return pool[Math.floor(Math.random() * pool.length)].id;
}

/**
 * 校验表情 ID 是否在候选表内（解析 LLM 输出用）。
 * @param {string} id - 待校验 ID
 * @returns {boolean} 在候选表内为 true
 */
export function isEmojiLike(id) {
  return EMOJI_LIKES.some((e) => e.id === String(id));
}
